def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="mcp-server-kit",
        description="Scaffold MCP servers with mcp-server-kit.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p_add = sub.add_parser(
        "add-server",
        help="Add a server to a clone of the mcp-server-kit repo (contributor mode).",
    )
    p_add.add_argument("name", help="PascalCase server name, e.g. 'Inventory'.")

    p_new = sub.add_parser(
        "new",
        help="Generate a new standalone MCP server project.",
    )
    p_new.add_argument("project_dir", help="Directory to create for the new project.")
    p_new.add_argument(
        "--standalone",
        "--vendor",
        dest="standalone",
        action="store_true",
        help="Vendor the base classes instead of depending on mcp-server-kit.",
    )
    ex = p_new.add_mutually_exclusive_group()
    ex.add_argument(
        "--with-examples",
        help="Comma-separated bundled servers to include (e.g. 'greet,weather').",
    )
    ex.add_argument(
        "--all-examples", action="store_true", help="Include all bundled servers."
    )
    ex.add_argument(
        "--no-examples", action="store_true", help="Include no bundled servers."
    )
    return parser


def main(argv: Optional[list] = None) -> None:
    args = build_parser().parse_args(argv)
    if args.command == "add-server":
        add_server(args.name)
    elif args.command == "new":
        examples = _resolve_examples(args)
        new_project(args.project_dir, args.standalone, examples)


if __name__ == "__main__":
    main()
