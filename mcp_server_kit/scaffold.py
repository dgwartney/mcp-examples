"""
Scaffolding CLI for mcp-server-kit.

Two subcommands:

    mcp-server-kit add-server <Name>
        In-repo contributor mode. Adds a new server module + test to a *clone*
        of the mcp-server-kit repository and registers it in ``combined.py`` and
        ``__init__.py``. Only valid when run from the repo root.

    mcp-server-kit new <project-dir> [--standalone] [--with-examples ... | --all-examples | --no-examples]
        Standalone project generator for installed users. Emits a brand-new,
        self-contained MCP server project in the current working directory that
        depends on (or vendors) mcp-server-kit.

Author:
    David Gwartney <david.gwartney@gmail.com>
"""

import argparse
import ast
import re
import sys
from pathlib import Path
from typing import Optional

# (prefix, ClassName, import_module) for each server bundled with mcp-server-kit.
BUNDLED_SERVERS = [
    ("greet", "GreetMCPServer", "mcp_server_kit.server"),
    ("contacts", "ContactMCPServer", "mcp_server_kit.contacts"),
    ("wikipedia", "WikipediaMCPServer", "mcp_server_kit.wikipedia"),
    ("weather", "WeatherMCPServer", "mcp_server_kit.weather"),
    ("messaging", "MessagingMCPServer", "mcp_server_kit.messaging"),
]
_BUNDLED_BY_PREFIX = {p: (p, c, m) for p, c, m in BUNDLED_SERVERS}

# Servers that need external-service env vars to actually function.
_ENV_DEPENDENT = {"weather", "messaging"}


def to_snake_case(name: str) -> str:
    """Convert a PascalCase/CamelCase name to snake_case."""
    s1 = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s1).lower()


def to_package_name(project_dir: str) -> str:
    """Derive a valid Python package name from a project directory name.

    ``my-mcp`` -> ``my_mcp``. Leading digits get an underscore prefix.
    """
    base = Path(project_dir).name
    pkg = re.sub(r"[^0-9a-zA-Z_]", "_", base).lower()
    pkg = re.sub(r"_+", "_", pkg).strip("_")
    if not pkg:
        raise ValueError(f"Cannot derive a package name from {project_dir!r}")
    if pkg[0].isdigit():
        pkg = f"_{pkg}"
    return pkg


