def _resolve_examples(args) -> list:
    """Determine which bundled servers to include, from flags or an interactive prompt."""
    if args.no_examples:
        return []
    if args.all_examples:
        return [p for p, _, _ in BUNDLED_SERVERS]
    if args.with_examples:
        chosen = [s.strip() for s in args.with_examples.split(",") if s.strip()]
        unknown = [c for c in chosen if c not in _BUNDLED_BY_PREFIX]
        if unknown:
            raise SystemExit(
                f"Error: unknown bundled server(s): {', '.join(unknown)}. "
                f"Choose from: {', '.join(p for p, _, _ in BUNDLED_SERVERS)}"
            )
        return chosen
    # No flag given: prompt interactively if we have a TTY, else default to none.
    if not sys.stdin.isatty():
        return []
    print("Which bundled example servers should be included? (y/N for each)")
    chosen = []
    for prefix, _cls, _mod in BUNDLED_SERVERS:
        note = " (needs API-key env vars)" if prefix in _ENV_DEPENDENT else ""
        answer = input(f"  include '{prefix}'{note}? [y/N] ").strip().lower()
        if answer in ("y", "yes"):
            chosen.append(prefix)
    return chosen


def _my_server_py(pkg: str, standalone: bool) -> str:
    base_import = (
        f"from {pkg}._base.base import AuthenticatedMCPServer, lazy_module_instances"
        if standalone
        else "from mcp_server_kit.base import AuthenticatedMCPServer, lazy_module_instances"
    )
    return f'''"""Your MCP server. Add tools inside ``_register_tools()``."""

{base_import}


class MyServer(AuthenticatedMCPServer):
    """A starter server with a single example tool."""

    def _register_tools(self) -> None:
        @self.mcp.tool(description="Add two numbers")
        def add(a: int, b: int) -> int:
            """Return the sum of two integers."""
            return a + b


# Lazy module-level ``server`` / ``mcp`` — built on first access, not on import.
__getattr__ = lazy_module_instances(MyServer)

if __name__ == "__main__":
    MyServer().main()
'''


def _combined_py(pkg: str, examples: list) -> str:
    imports = [f"from {pkg}.my_server import MyServer"]
    registry = ['    ("my_server", MyServer),']
    for prefix in examples:
        _p, cls, mod = _BUNDLED_BY_PREFIX[prefix]
        imports.append(f"from {mod} import {cls}")
        registry.append(f'    ("{prefix}", {cls}),')
    imports_block = "\n".join(imports)
    registry_block = "\n".join(registry)
    return f'''"""Combined ASGI app mounting every server in SERVER_REGISTRY at its own path."""

import argparse
from contextlib import AsyncExitStack, asynccontextmanager

import uvicorn
from starlette.applications import Starlette
from starlette.routing import Mount

{imports_block}

# To add a server: append (url_prefix, ServerClass) here.
SERVER_REGISTRY = [
{registry_block}
]


def _build():
    routes, sub_apps, servers = [], [], []
    for prefix, ServerClass in SERVER_REGISTRY:
        srv = ServerClass()
        sub_app = srv.mcp.http_app(
            path="/mcp",
            middleware=srv._http_middleware,
            transport="streamable-http",
        )
        routes.append(Mount(f"/{{prefix}}", app=sub_app))
        sub_apps.append(sub_app)
        servers.append(srv)
    return routes, sub_apps, servers


def build_app() -> Starlette:
    routes, sub_apps, servers = _build()

    @asynccontextmanager
    async def _lifespan(parent_app):
        # Starlette's Mount does not propagate sub-app lifespans automatically;
        # compose them here so each server's background workers start and stop
        # correctly.
        try:
            async with AsyncExitStack() as stack:
                for sub_app in sub_apps:
                    await stack.enter_async_context(sub_app.lifespan(sub_app))
                yield
        finally:
            for srv in servers:
                srv.close()

    return Starlette(lifespan=_lifespan, routes=routes)


_app_cache = {{}}


def __getattr__(name):
    if name == "app":
        if "app" not in _app_cache:
            _app_cache["app"] = build_app()
        return _app_cache["app"]
    raise AttributeError(f"module {{__name__!r}} has no attribute {{name!r}}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Combined MCP Server")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8000)
    args = parser.parse_args()
    uvicorn.run("{pkg}.combined:app", host=args.host, port=args.port)
'''


def _test_my_server_py(pkg: str) -> str:
    return f'''"""Tests for the generated MyServer.

Uses fastmcp's public in-memory ``Client`` (stable across fastmcp versions)
rather than private internals.
"""

import asyncio

from fastmcp import Client

from {pkg}.my_server import MyServer


def test_add_tool_registered_and_works(tmp_path):
    srv = MyServer(db_path=str(tmp_path / "keys.db"))

    async def _check():
        async with Client(srv.mcp) as client:
            tools = {{t.name for t in await client.list_tools()}}
            assert "add" in tools
            result = await client.call_tool("add", {{"a": 2, "b": 3}})
            assert result.data == 5

    asyncio.run(_check())


def test_import_creates_no_db(tmp_path, monkeypatch):
    """Importing the server module must not create a database on disk."""
    monkeypatch.chdir(tmp_path)
    import importlib

    import {pkg}.my_server as m

    importlib.reload(m)
    assert not list(tmp_path.glob("*.db"))
'''


def _pyproject(project_name: str, pkg: str, standalone: bool, needs_kit: bool) -> str:
    deps = []
    if standalone:
        deps += [
            '    "fastmcp>=2.14.5",',
            '    "httpx>=0.27.0",',
            '    "starlette>=0.37.0",',
            '    "uvicorn>=0.30.0",',
        ]
    if not standalone or needs_kit:
        deps.append('    "mcp-server-kit>=0.1.0",')
    deps_block = "\n".join(deps)
    return f'''[project]
name = "{project_name}"
version = "0.1.0"
description = "An MCP server generated with mcp-server-kit."
requires-python = ">=3.10"
dependencies = [
{deps_block}
]

[project.optional-dependencies]
test = [
    "pytest>=8.0.0",
    "httpx>=0.27.0",
]

[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[tool.hatch.build.targets.wheel]
packages = ["{pkg}"]
'''


def _readme(project_name: str, pkg: str, standalone: bool, examples: list, needs_kit: bool) -> str:
    lines = [
        f"# {project_name}",
        "",
        "An MCP server generated with [mcp-server-kit](https://pypi.org/project/mcp-server-kit/).",
        "",
        "## Install & run",
        "",
        "This project uses [uv](https://github.com/astral-sh/uv) — not pip.",
        "",
        "```bash",
        "uv sync",
        f"uv run python -m {pkg}.combined --port 8000   # serves /my_server/mcp",
        "```",
        "",
        "The combined server prints a generated API key on first run (via logging). ",
        "Send it as the `X-API-Key` header when calling tools.",
        "",
        "## Add tools",
        "",
        f"Edit `{pkg}/my_server.py` and add tools inside `_register_tools()`.",
        "",
    ]
    if standalone and needs_kit:
        lines += [
            "> **Note:** you selected `--standalone` but also included bundled example ",
            "> servers, which are imported from the `mcp-server-kit` package. As a result ",
            "> `mcp-server-kit` remains a dependency of this project. Remove the bundled ",
            "> servers from `combined.py` (and the dependency from `pyproject.toml`) for a ",
            "> fully dependency-free project.",
            "",
        ]
    env_needed = [e for e in examples if e in _ENV_DEPENDENT]
    if env_needed:
        lines += [
            f"> **Note:** the bundled `{', '.join(env_needed)}` server(s) require API-key ",
            "> environment variables to function (e.g. `OPENWEATHER_API_KEY`, "
            "`TWILIO_ACCOUNT_SID`).",
            "",
        ]
    return "\n".join(lines)


def _vendor_base(project_path: Path, pkg: str) -> None:
    """Copy base.py/middleware.py/database.py into <pkg>/_base/ with rewritten imports."""
    import mcp_server_kit

    src_dir = Path(mcp_server_kit.__file__).parent
    base_dir = project_path / pkg / "_base"
    base_dir.mkdir(parents=True, exist_ok=True)
    (base_dir / "__init__.py").write_text('"""Vendored mcp-server-kit base classes."""\n')
    for fname in ("database.py", "middleware.py", "base.py"):
        text = (src_dir / fname).read_text()
        text = text.replace(
            "from mcp_server_kit.database import", f"from {pkg}._base.database import"
        )
        text = text.replace(
            "from mcp_server_kit.middleware import", f"from {pkg}._base.middleware import"
        )
        (base_dir / fname).write_text(text)


def new_project(
    project_dir: str,
    standalone: bool,
    examples: list,
) -> Path:
    """Generate a standalone MCP server project directory. Returns its path."""
    project_path = Path(project_dir)
    if project_path.exists() and any(project_path.iterdir()):
        raise SystemExit(f"Error: {project_path} already exists and is not empty.")

    pkg = to_package_name(project_dir)
    project_name = project_path.name
    needs_kit = bool(examples)  # bundled servers import from mcp_server_kit

    (project_path / pkg).mkdir(parents=True, exist_ok=True)
    (project_path / "tests").mkdir(parents=True, exist_ok=True)

    (project_path / pkg / "__init__.py").write_text('__version__ = "0.1.0"\n')
    (project_path / pkg / "my_server.py").write_text(_my_server_py(pkg, standalone))
    (project_path / pkg / "combined.py").write_text(_combined_py(pkg, examples))
    (project_path / "tests" / "__init__.py").write_text("")
    (project_path / "tests" / "test_my_server.py").write_text(_test_my_server_py(pkg))
    (project_path / "pyproject.toml").write_text(
        _pyproject(project_name, pkg, standalone, needs_kit)
    )
    (project_path / "README.md").write_text(
        _readme(project_name, pkg, standalone, examples, needs_kit)
    )
    if standalone:
        _vendor_base(project_path, pkg)

    print(f"Created project {project_path}/ (package '{pkg}')")
    if examples:
        print(f"  bundled servers: {', '.join(examples)}")
    print(f"  mode: {'standalone (vendored base)' if standalone else 'depends on mcp-server-kit'}")
    if standalone and needs_kit:
        print("  note: bundled servers keep mcp-server-kit as a dependency (see README).")
    print()
    print("Next steps:")
    print(f"  cd {project_path} && uv sync --extra test")
    print(f"  uv run python -m {pkg}.combined --port 8000")
    return project_path


