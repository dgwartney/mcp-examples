_TEMPLATE_INTRO = """Copy this file, rename the class and the module, and replace `example_tool`
with your own tool(s). This is the smallest possible AuthenticatedMCPServer
subclass — no external API calls, no SQLite domain tables beyond the
built-in API-key auth store.

See docs/extending.md for the full checklist of what else to update when
adding a new server (combined.py's SERVER_REGISTRY, docs/servers.md, tests)."""


def _find_repo_root() -> Path:
    """Locate the repo root by walking up from CWD looking for the package layout."""
    for candidate in (Path.cwd(), *Path.cwd().parents):
        if (candidate / "mcp_server_kit" / "combined.py").exists() and (
            candidate / "tests"
        ).is_dir():
            return candidate
    raise SystemExit(
        "Error: 'add-server' must be run from a clone of the mcp-server-kit repo "
        "(no mcp_server_kit/combined.py + tests/ found in the current directory or "
        "its parents).\n"
        "If you installed mcp-server-kit and want to start your own project, "
        "use 'mcp-server-kit new <project-dir>' instead."
    )


def _render_repo_module(template: str, name: str, name_snake: str) -> str:
    """Render a new in-repo server module from mcp_server_kit/_template.py."""
    generated_intro = (
        "Generated by 'mcp-server-kit add-server' from mcp_server_kit/_template.py.\n"
        "Replace `example_tool` with your own tool(s) in _register_tools()."
    )
    rendered = template.replace(_TEMPLATE_INTRO, generated_intro)
    rendered = rendered.replace(
        "Minimal starter template for a new MCP server.", f"{name} MCP server."
    )
    rendered = rendered.replace("Template", name)
    rendered = rendered.replace("mcp_server_kit._template", f"mcp_server_kit.{name_snake}")
    return rendered


def _render_repo_test(template: str, name: str, name_snake: str) -> str:
    """Render a new in-repo test module from tests/test__template.py."""
    rendered = template.replace("Template", name)
    rendered = rendered.replace("mcp_server_kit._template", f"mcp_server_kit.{name_snake}")
    rendered = rendered.replace("template_module", f"{name_snake}_module")
    return rendered


def _closing_index(lines: list[str], name: str, closer: str) -> int:
    """
    Index of the line closing the ``name = [...]`` / ``{...}`` literal: the
    first line equal to ``closer`` after the line that assigns ``name``.
    (A fixed look-back window broke once a registry grew past it.)
    """
    start = next(
        (i for i, line in enumerate(lines)
         if line.lstrip().startswith(name) and "=" in line),
        None,
    )
    if start is None:
        raise RuntimeError(f"Could not find {name} in the file being updated")
    for i in range(start + 1, len(lines)):
        if lines[i].strip() == closer:
            return i
    raise RuntimeError(f"Could not find the closing {closer!r} of {name}")


def _update_combined_py(repo_root: Path, name: str, name_snake: str) -> None:
    """Add an import line and a SERVER_REGISTRY entry to combined.py."""
    combined_path = repo_root / "mcp_server_kit" / "combined.py"
    lines = combined_path.read_text().splitlines(keepends=True)

    import_line = f"from mcp_server_kit.{name_snake} import {name}MCPServer\n"
    import_indices = [
        i
        for i, line in enumerate(lines)
        if line.startswith("from mcp_server_kit.") and " import " in line
    ]
    if not import_indices:
        raise RuntimeError("Could not find the mcp_server_kit import block in combined.py")
    insert_at = import_indices[-1] + 1
    for i in import_indices:
        if lines[i] > import_line:
            insert_at = i
            break
    lines.insert(insert_at, import_line)

    registry_entry = f'    ("{name_snake}", {name}MCPServer),\n'
    closing_bracket_idx = _closing_index(lines, "SERVER_REGISTRY", "]")
    lines.insert(closing_bracket_idx, registry_entry)

    combined_path.write_text("".join(lines))
    ast.parse(combined_path.read_text())


def _update_init_py(repo_root: Path, name: str, name_snake: str) -> None:
    """Add the new server class to __init__.py's __all__ and _LAZY_IMPORTS."""
    init_path = repo_root / "mcp_server_kit" / "__init__.py"
    lines = init_path.read_text().splitlines(keepends=True)
    class_name = f"{name}MCPServer"

    all_closing_idx = _closing_index(lines, "__all__", "]")
    lines.insert(all_closing_idx, f'    "{class_name}",\n')

    lazy_closing_idx = _closing_index(lines, "_LAZY_IMPORTS", "}")
    lines.insert(lazy_closing_idx, f'    "{class_name}": "mcp_server_kit.{name_snake}",\n')

    init_path.write_text("".join(lines))
    ast.parse(init_path.read_text())


def add_server(name: str) -> None:
    """Add a new server to a clone of the mcp-server-kit repo (contributor mode)."""
    if not name.isidentifier() or not name[0].isupper():
        raise SystemExit(
            f"Error: '{name}' must be a valid PascalCase identifier (e.g. 'Inventory')."
        )

    repo_root = _find_repo_root()
    package_dir = repo_root / "mcp_server_kit"
    tests_dir = repo_root / "tests"
    name_snake = to_snake_case(name)
    module_path = package_dir / f"{name_snake}.py"
    test_path = tests_dir / f"test_{name_snake}.py"

    for path in (module_path, test_path):
        if path.exists():
            raise SystemExit(f"Error: {path} already exists — refusing to overwrite.")

    module_template = (package_dir / "_template.py").read_text()
    test_template = (tests_dir / "test__template.py").read_text()

    module_path.write_text(_render_repo_module(module_template, name, name_snake))
    test_path.write_text(_render_repo_test(test_template, name, name_snake))
    _update_combined_py(repo_root, name, name_snake)
    _update_init_py(repo_root, name, name_snake)

    print(f"Created {module_path.relative_to(repo_root)}")
    print(f"Created {test_path.relative_to(repo_root)}")
    print(f"Updated mcp_server_kit/combined.py (added {name}MCPServer to SERVER_REGISTRY)")
    print(f"Updated mcp_server_kit/__init__.py (added {name}MCPServer to __all__/_LAZY_IMPORTS)")
    print()
    print("Remaining steps (see docs/extending.md):")
    print(f"  1. Implement your tools in {module_path.relative_to(repo_root)}'s _register_tools()")
    print("  2. Add a section for it in docs/servers.md")
    print(f"  3. Fill in {test_path.relative_to(repo_root)} with real test cases")
    print("  4. Run: uv run pytest")
    print("  5. Start the combined server and curl the new endpoint:")
    print("     uv run -m mcp_server_kit.combined --port 8000")
    print(f"     curl -X POST http://localhost:8000/{name_snake}/mcp ...")


